def get_all_states():
    return sorted(list(INDIA_STATES_DISTRICTS.keys()))

def get_districts_by_state(state_name):
    if state_name in INDIA_STATES_DISTRICTS:
        return sorted(list(INDIA_STATES_DISTRICTS[state_name].keys()))
    return []

def get_district_info(state_name, district_name):
    if state_name in INDIA_STATES_DISTRICTS:
        districts = INDIA_STATES_DISTRICTS[state_name]
        if district_name in districts:
            return districts[district_name]
        # Case insensitive search
        for d, info in districts.items():
            if d.lower() == district_name.lower():
                return info
    return None

def find_district_by_name(query):
    """Search for a district across all states of India"""
    q = query.strip().lower()
    for state, districts in INDIA_STATES_DISTRICTS.items():
        for dist, info in districts.items():
            if q == dist.lower() or q in dist.lower():
                return {
                    "district": dist,
                    "state": state,
                    "lat": info["lat"],
                    "lon": info["lon"],
                    "zone": info["zone"]
                }
    return None
